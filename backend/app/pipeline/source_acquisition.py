"""
source_acquisition.py — Candidate collection, URL normalization, deduplication, and ranking.

NO LLM is used in this module.
"""
from __future__ import annotations

import asyncio
from typing import List, Optional
from urllib.parse import parse_qsl, urlencode, urlparse, urlunparse

from pydantic import BaseModel

from ..models import ExpectedTopic
from .classify import classify_source, extract_domain
from .queries import generate_queries
from .search import SearchResult, search

# Query parameters commonly used for marketing/tracking that should be stripped
TRACKING_PARAMS = {
    "utm_source",
    "utm_medium",
    "utm_campaign",
    "utm_term",
    "utm_content",
    "fbclid",
    "gclid",
    "ref",
    "source",
    "v",
    "mc_cid",
    "mc_eid",
    "trk",
    "msclkid",
}


def normalize_url(url: str) -> str:
    """Normalize URL by stripping tracking parameters, fragments, and trailing slashes."""
    if not url:
        return ""
    try:
        parsed = urlparse(url.strip())
        # Lowercase scheme and hostname
        scheme = (parsed.scheme or "http").lower()
        netloc = (parsed.netloc or "").lower()

        # Remove default ports
        if netloc.endswith(":80") and scheme == "http":
            netloc = netloc[:-3]
        elif netloc.endswith(":443") and scheme == "https":
            netloc = netloc[:-4]

        # Normalize path
        path = parsed.path or "/"
        if len(path) > 1 and path.endswith("/"):
            path = path[:-1]

        # Filter out tracking query params
        query_pairs = parse_qsl(parsed.query, keep_blank_values=False)
        cleaned_pairs = [
            (k, v) for k, v in query_pairs if k.lower() not in TRACKING_PARAMS
        ]
        query = urlencode(cleaned_pairs) if cleaned_pairs else ""

        # Remove fragment
        fragment = ""

        return urlunparse((scheme, netloc, path, parsed.params, query, fragment))
    except Exception:
        return url.strip().rstrip("/")


class CollectResult(BaseModel):
    """Result of source candidate collection."""
    candidates: list[SearchResult]
    warnings: list[str] = []


async def collect_candidates(
    entity: str,
    topics: List[ExpectedTopic],
    extra_urls: Optional[List[str]] = None,
    max_sources: int = 8,
    *,
    use_cache: bool = True,
) -> CollectResult:
    """Collect, deduplicate, filter, and rank source candidates.

    Rules:
    - Runs queries generated by queries.py in parallel (concurrency limited).
    - Deduplicates by normalized URL.
    - Limits to at most 2 results per domain.
    - Incorporates user-supplied extra_urls with top priority.
    - Ranks official sources first, followed by relevance and search score.
    - Never crashes if search fails; adds a warning and continues with extra_urls.
    - If no official-looking source exists among candidates, emits a clear warning.
    """
    warnings: list[str] = []
    candidates_by_url: dict[str, SearchResult] = {}
    extra_urls = extra_urls or []

    # 1. Add extra user-supplied URLs first
    for u in extra_urls:
        norm = normalize_url(u)
        if norm and norm not in candidates_by_url:
            candidates_by_url[norm] = SearchResult(
                url=norm,
                title=u,
                snippet="User-supplied source URL",
                score=1.0,
            )

    # 2. Generate search queries
    search_queries = generate_queries(entity, topics, max_queries=5)

    # 3. Execute searches concurrently with bounded semaphore
    semaphore = asyncio.Semaphore(3)

    async def _run_single_query(q: str) -> list[SearchResult]:
        async with semaphore:
            try:
                return await search(q, max_results=5, use_cache=use_cache)
            except Exception as exc:
                warnings.append(f"Search query failed for {q!r}: {exc}")
                return []

    query_tasks = [_run_single_query(q) for q in search_queries]
    batch_results = await asyncio.gather(*query_tasks)

    # Flatten and add candidates
    for sublist in batch_results:
        for r in sublist:
            norm = normalize_url(r.url)
            if not norm:
                continue
            if norm not in candidates_by_url:
                candidates_by_url[norm] = r
            else:
                # Retain higher score or raw content if available
                existing = candidates_by_url[norm]
                if not existing.content and r.content:
                    existing.content = r.content
                if (existing.score or 0.0) < (r.score or 0.0):
                    existing.score = r.score

    # 4. Filter: Max 2 results per domain, prioritizing official & highest score
    domain_counts: dict[str, int] = {}
    filtered_list: list[tuple[SearchResult, str, float]] = []

    # Score each candidate for ranking
    entity_words = [w.lower() for w in entity.split() if len(w) > 2]

    for norm_url, cand in candidates_by_url.items():
        domain = extract_domain(norm_url)
        s_class = classify_source(norm_url, title=cand.title, entity=entity)

        # Ranking score:
        # User supplied: 100+
        # Official: 50+
        # Entity name in title/url: +10
        # Tavily search score: (0.0 to 1.0) * 10
        rank_weight = 0.0
        if norm_url in [normalize_url(u) for u in extra_urls]:
            rank_weight += 100.0
        if s_class == "official":
            rank_weight += 50.0
        elif s_class == "news":
            rank_weight += 20.0
        elif s_class == "aggregator":
            rank_weight += 10.0

        title_lower = cand.title.lower() if cand.title else ""
        if any(w in title_lower or w in norm_url for w in entity_words):
            rank_weight += 15.0

        if cand.score is not None:
            rank_weight += cand.score * 10.0

        filtered_list.append((cand, domain, rank_weight))

    # Sort descending by ranking score
    filtered_list.sort(key=lambda x: x[2], reverse=True)

    # Apply per-domain cap of 2
    final_candidates: list[SearchResult] = []
    has_official = False

    for cand, domain, _ in filtered_list:
        count = domain_counts.get(domain, 0)
        # Exception: user explicitly supplied URLs always bypass the domain cap
        is_user_supplied = normalize_url(cand.url) in [normalize_url(u) for u in extra_urls]
        if count < 2 or is_user_supplied:
            final_candidates.append(cand)
            domain_counts[domain] = count + 1
            if classify_source(cand.url, title=cand.title, entity=entity) == "official":
                has_official = True

        if len(final_candidates) >= max_sources:
            break

    # 5. Check if official source was found
    if not has_official:
        warnings.append("No official-looking source found among candidates")

    return CollectResult(candidates=final_candidates, warnings=warnings)

